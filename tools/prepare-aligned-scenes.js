// Extract/encode RGBA atlas cells and measure their structural ground anchors.
// Alignment lives in CSS coordinates; illustration pixels are not repainted.
const fs=require('node:fs'),path=require('node:path'),sharp=require(process.env.SHARP_MODULE||'sharp');
const root=path.resolve(__dirname,'..'),sources=require('../art-source/realm-scenes-v2/sources.json');
const stages=['ruins','foundation','walls','restored','celebrated'];
async function measure(file){
  const {data,info}=await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject:true});
  const {width:w,height:h}=info;let total=0,clear=0,baseline=-1;
  const rows=[];
  for(let y=0;y<h;y++){let n=0;for(let x=0;x<w;x++){const a=data[(y*w+x)*4+3];if(a>192){n++;total++;}if(a===0)clear++;}rows.push(n);if(n>=w*.35)baseline=y;}
  if(clear<w*h*.1||baseline<0)throw new Error(`Missing transparent landmark or ground anchor: ${file}`);
  let left=w,right=0;
  for(let y=Math.max(0,baseline-Math.round(h*.035));y<=baseline;y++)for(let x=0;x<w;x++)if(data[(y*w+x)*4+3]>192){left=Math.min(left,x);right=Math.max(right,x);}
  return {width:w,height:h,left:left/w,right:right/w,baseline:baseline/h,transparentFraction:clear/(w*h)};
}
(async()=>{
  const manifest=[],registration={};
  for(const {family,source} of sources){
    const master=path.join(root,`art-source/realm-scenes-v2/x${family}-atlas.png`);if(!fs.existsSync(master))fs.copyFileSync(source,master);
    const {width,height}=await sharp(master).metadata(),out=path.join(root,`public/art/realm/scenes/x${family}`);fs.mkdirSync(out,{recursive:true});
    for(let i=0;i<5;i++){
      const left=Math.round(i%2*width/2),top=Math.round(Math.floor(i/2)*height/3),w=Math.round((i%2+1)*width/2)-left,h=Math.round((Math.floor(i/2)+1)*height/3)-top;
      const dest=path.join(out,`${stages[i]}-v2.webp`);
      const info=await sharp(master).extract({left,top,width:w,height:h}).webp({quality:86,alphaQuality:100,effort:6}).toFile(dest);
      manifest.push({family,stage:stages[i],path:path.relative(path.join(root,'public'),dest).replaceAll('\\','/'),bytes:info.size,...await measure(dest)});
    }
  }
  // The approved pilot already has true alpha; register its existing sprites too.
  for(const stage of stages){const file=path.join(root,`public/art/realm/squarestone/${stage}-v1.webp`);manifest.push({family:4,stage,path:`art/realm/squarestone/${stage}-v1.webp`,bytes:fs.statSync(file).size,...await measure(file)});}
  for(let f=0;f<=12;f++){
    const frames=manifest.filter(m=>m.family===f),ref=frames.find(m=>m.stage==='restored');registration[f]={};
    for(const frame of frames){const scale=(ref.right-ref.left)/(frame.right-frame.left);registration[f][frame.stage]={left:100*(ref.left-frame.left*scale),top:100*(ref.baseline-frame.baseline*scale),scale};}
  }
  fs.writeFileSync(path.join(root,'art-source/realm-scenes-v2/manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  fs.writeFileSync(path.join(root,'public/realm-scene-registration.js'),`/* Measured ground anchors; regenerated by tools/prepare-aligned-scenes.js. */\n(function(root){const registration=${JSON.stringify(registration)};root.RealmSceneRegistration=registration;if(typeof module!=='undefined'&&module.exports)module.exports=registration;})(typeof window!=='undefined'?window:globalThis);\n`);
  console.log(`${manifest.length} registered stages; ${manifest.filter(m=>m.family!==4).reduce((n,m)=>n+m.bytes,0)} bytes of new alpha art`);
  console.log(JSON.stringify(registration,null,2));
})().catch(e=>{console.error(e);process.exitCode=1;});
